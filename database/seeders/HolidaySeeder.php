 *
 * วันที่เก็บเป็น พ.ศ. ให้ตรงกับ visits.appointment
 * คอลัมน์สุดท้ายของแต่ละแถวคือ "วันในสัปดาห์ที่ควรจะเป็น" — ไม่ได้เก็บลงฐานข้อมูล
 * มีไว้ให้ seeder ตรวจว่าลอกวันที่มาถูกไหม ถ้าไม่ตรงจะหยุดทันทีแทนที่จะใส่วันผิดเข้าไปเงียบๆ
 * (ลอกจากตารางด้วยมือ ผิดได้ง่ายมาก และผิดแล้วจะไปโผล่เป็นนัดที่คลินิกปิด)
