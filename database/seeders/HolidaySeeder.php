    private const DAYS = ['อาทิตย์', 'จันทร์', 'อังคาร', 'พุธ', 'พฤหัสบดี', 'ศุกร์', 'เสาร์'];

    public function run()
    {
        $rows = array_merge($this->year2569(), $this->year2570());

        $mismatch = [];
        foreach ($rows as $r) {
            [$date, $name, $type, $note, $expectDay] = $r;
            $actual = self::DAYS[(int) date('w', strtotime(Utillity::BE2AD($date)))];
            if ($actual !== $expectDay) {
                $mismatch[] = "{$date} {$name} — ตารางบอก {$expectDay} แต่ปฏิทินจริงเป็น {$actual}";
            }
        }
        if ($mismatch) {
            $this->command->error('วันที่กับวันในสัปดาห์ไม่ตรงกัน ยังไม่ได้บันทึกอะไรลงฐานข้อมูล:');
            foreach ($mismatch as $m) {
                $this->command->error('  - ' . $m);
            }
            return;
        }

        $added = 0;
        $kept  = 0;
        foreach ($rows as [$date, $name, $type, $note, $_]) {
            // updateOrCreate จะทับของที่พยาบาลแก้เอาไว้เอง จึงเพิ่มเฉพาะวันที่ยังไม่มี
            if (Holiday::where('holiday_date', $date)->exists()) {
                $kept++;
                continue;
            }
            Holiday::create([
                'holiday_date' => $date,
                'name'         => $name,
                'type'         => $type,
                'note'         => $note,
                'is_closed'    => true,
            ]);
            $added++;
        }

        $this->command->info("เพิ่มวันหยุด {$added} วัน · ข้ามของเดิมที่มีอยู่แล้ว {$kept} วัน");
    }

