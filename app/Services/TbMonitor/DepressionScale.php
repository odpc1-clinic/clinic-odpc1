    /**
     * คิดคะแนน + แปลผลจากคำตอบดิบ
     * $q2 = [1 => 0|1, 2 => 0|1] · $q9 = [1..9 => 0-3] หรือ null (ไม่ได้ทำ) · $q8 = ['1' => 0|1, ...] หรือ null
     * คืน ['q2_positive', 'q9_score', 'q9_level', 'need_9q', 'q8_score', 'q8_level', 'need_8q', 'interpretation', 'refer']
     */
    public static function evaluate(array $q2, ?array $q9 = null, ?array $q8 = null): array
    {
        $q2pos = ! empty($q2[1]) || ! empty($q2[2]);

        $q9score = null; $q9level = null;
        if ($q9 !== null && $q9 !== []) {
            $q9score = 0;
            foreach (self::Q9 as $k => $_) { $q9score += max(0, min(3, (int) ($q9[$k] ?? 0))); }
            $q9level = self::q9Level($q9score);
        }
        // 9Q ข้อ 9 (คิดทำร้ายตนเอง) ตอบว่ามี = ต้องประเมิน 8Q ต่อแม้คะแนนรวมไม่ถึง 7 (ไม่ปล่อยหลุดความเสี่ยงฆ่าตัวตาย)
        $need8 = $q9score !== null && ($q9score >= 7 || (int) ($q9[9] ?? 0) > 0);

        $q8score = null; $q8level = null;
        if ($q8 !== null && $q8 !== []) {
            $q8score = 0;
            foreach (self::Q8 as $k => [$_, $pt]) {
                if ($k === '3a' && empty($q8['3'])) { continue; }   // 3a นับเฉพาะเมื่อข้อ 3 ตอบว่ามี
                if (! empty($q8[$k])) { $q8score += $pt; }
            }
            $q8level = self::q8Level($q8score);
        }

        $parts = [];
        $parts[] = '2Q ' . ($q2pos ? 'บวก (มีความเสี่ยง)' : 'ลบ (ไม่เป็นโรคซึมเศร้า)');
        if ($q9score !== null) { $parts[] = '9Q = ' . $q9score . ' ' . $q9level; }
        if ($q8score !== null) { $parts[] = '8Q = ' . $q8score . ' ' . $q8level; }

        return [
            'q2_positive' => $q2pos,
            'need_9q'     => $q2pos,
            'q9_score'    => $q9score,
            'q9_level'    => $q9level,
            'need_8q'     => $need8,
            'q8_score'    => $q8score,
            'q8_level'    => $q8level,
            'interpretation' => implode(' · ', $parts),
            // ส่งต่อ: ซึมเศร้าปานกลางขึ้นไป หรือมีความเสี่ยงฆ่าตัวตายใด ๆ (ตามแนวทางกรมสุขภาพจิต)
            'refer'       => ($q9score !== null && $q9score >= 13) || ($q8score !== null && $q8score >= 1),
        ];
    }

    public static function q9Level(int $s): string
    {
        if ($s < 7)   { return 'ไม่มีอาการ/มีอาการน้อยมาก'; }
        if ($s <= 12) { return 'ซึมเศร้าระดับน้อย'; }
        if ($s <= 18) { return 'ซึมเศร้าระดับปานกลาง'; }
        return 'ซึมเศร้าระดับรุนแรง';
    }

    public static function q8Level(int $s): string
    {
        if ($s === 0) { return 'ไม่มีแนวโน้มฆ่าตัวตาย'; }
        if ($s <= 8)  { return 'แนวโน้มฆ่าตัวตายระดับน้อย'; }
        if ($s <= 16) { return 'แนวโน้มฆ่าตัวตายระดับปานกลาง'; }
        return 'แนวโน้มฆ่าตัวตายระดับรุนแรง';
    }
